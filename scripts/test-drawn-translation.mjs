import assert from 'node:assert/strict';
import {ctx,ui,data,style,group,layoutCounters} from './test-drawn-text-row.mjs';
const original=group('original https://original.test');
const engine=new ctx.DrawnTextLayouts();
const plain=engine.prepare(ui,original,data,style);
const pending=engine.prepare(ui,original,data,{...style,translationStatus:{phase:'loading',error:''}});
assert.ok(pending);assert.equal(pending.caption.paragraph.parts[0].paragraph,plain.caption.paragraph,'status must retain original paragraph');
assert.ok(pending.caption.accessibilityText.includes('mb_translating'));
const failed=engine.prepare(ui,original,data,{...style,translationStatus:{phase:'failed',error:'network failed'}});
assert.ok(failed.caption.hits.some(h=>h.link.action==='translation-retry'));
assert.equal(failed.caption.paragraph.parts[0].paragraph,plain.caption.paragraph);
const translated={...original,head:{...original.head,translatedText:'translated link',translatedEntities:[{offset:11,length:4,type:{'@type':'textEntityTypeTextUrl',url:'https://translated.test'}}],translatedLang:'en',translationHidden:false}};
const both=engine.prepare(ui,translated,data,style);
assert.ok(both.caption.hits.some(h=>h.link.url==='https://original.test'));
assert.ok(both.caption.hits.some(h=>h.link.url==='https://translated.test'));
assert.ok(both.caption.hits.some(h=>h.link.action==='translation-toggle'));
const replace=engine.prepare(ui,translated,data,{...style,replaceTranslation:true});
assert.ok(!replace.caption.hits.some(h=>h.link.url==='https://original.test'));
assert.ok(replace.caption.hits.some(h=>h.link.url==='https://translated.test'));
const hidden=engine.prepare(ui,{...translated,head:{...translated.head,translationHidden:true}},data,{...style,replaceTranslation:true});
assert.ok(hidden.caption.hits.some(h=>h.link.url==='https://original.test'));
assert.ok(!hidden.caption.hits.some(h=>h.link.url==='https://translated.test'));
const warm=engine.prepare(ui,translated,data,style),before=layoutCounters();
for(let i=0;i<1000;i++)assert.equal(engine.prepare(ui,translated,data,style),warm);
assert.deepEqual(layoutCounters(),before);
assert.ok(ctx.drawnTextRowEligible(translated,data,false,false));
console.log('PASS: loading/failed/translation/show-hide/replace preserve row route, original paragraph identity, translated entity links and 1000 warm cache hits.');
