import assert from 'node:assert/strict';
import {ctx,load,compiled,ui,data,style,group} from './test-drawn-text-row.mjs';
load(compiled+'pages/chat/DrawnRowAccessibility.ts',['DrawnRowAccessibility']);
const message=group('visible secret link',[{offset:8,length:6,type:{'@type':'textEntityTypeSpoiler'}},{offset:15,length:4,type:{'@type':'textEntityTypeTextUrl',url:'https://visible.test'}}]);
Object.assign(message.head,{senderName:'Sender',isOutgoing:true});
const plan=new ctx.DrawnTextLayouts().prepare(ui,message,data,style);
const view=Object.assign(Object.create(ctx.DrawnRowAccessibility.prototype),{plan,msg:message.head,sendState:'sending'});
const targets=view.targets;
assert.ok(targets[0].label.includes('a11y_message_sending'));
assert.ok(!targets[0].label.includes('secret'),'spoken body must not reveal concealed text');
assert.ok(targets.some(t=>t.label==='link'));
assert.ok(targets.some(t=>t.label==='mb_spoiler'));
const calls=[];view.onActivate=(...a)=>calls.push(a);view.onMenu=()=>calls.push('menu');
Object.defineProperty(view,'targets',{value:targets,configurable:true});
view.activate(targets[0],{});assert.equal(calls[0],'menu');
const link=targets.find(t=>t.label==='link');view.activate(link,{});assert.equal(calls.length,2);
assert.equal(calls[1][0],link.x+link.width/2);
Object.defineProperty(view,'targets',{value:[],configurable:true});view.activate(link,{});assert.equal(calls.length,2,'stale semantic target cannot act after recycling');
assert.equal(ctx.drawnTextRowEligible(message,data,false,true),true);
console.log('PASS: same-row semantic descendants, concealed content, send status, distinct link/reveal actions and stale-target isolation.');
